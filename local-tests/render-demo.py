"""Render flagship demo scenarios A/B/C artifacts (offline, deterministic).

Rebuilds: python local-tests/render-demo.py
Outputs: local-tests/closure-demo-{A,B,C}.rendered.md (before/after Proof
Graph, section 7 P1/P2 actions, Recovery Delta, Readiness Passport).
Local simulation only -- not NAS runtime evidence.
"""

import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import harness
import proofgraph

VERSION = "v8"


def section7(report: str) -> str:
    body = report.split("## 7. Next steps")[1].split("## 8. Verdict")[0]
    return "## 7. Next steps" + body.rstrip()


def doc_for(tag: str, title: str, project: str, scope: str,
            scenario: str, before: dict, after: dict) -> list[str]:
    assert proofgraph.check_consistency(before) == []
    assert proofgraph.check_consistency(after) == []
    return [
        f"# Flagship demo, scenario {tag} -- rendered artifacts",
        "",
        f"## {title}",
        "",
        "Generated by `local-tests/render-demo.py` (deterministic).",
        "Local simulation of the Skill contract -- not NAS runtime evidence.",
        "",
        "## Before: Proof Graph (blocker present)",
        "",
        "```text",
        proofgraph.render_graph(before),
        "```",
        "",
        "## Before: recommended actions (P1/P2)",
        "",
        "```text",
        section7(before["report"]),
        "```",
        "",
        "## After fix + recheck: Proof Graph with Delta",
        "",
        "```text",
        proofgraph.render_delta_graph(after),
        "```",
        "",
        "## After: Readiness Passport",
        "",
        proofgraph.render_passport(
            after, project=project, scope=scope,
            scenario=scenario, version=VERSION,
            assessed_at="demo render (no live clock)"),
        "",
    ]


def scenario_a() -> tuple:
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp) / "a"
        shutil.copytree(HERE / "corpus" / "core-a", t)
        before = harness.run(t)
        (t / "config").mkdir(parents=True, exist_ok=True)
        (t / "config" / "prod-config.yaml").write_text(
            "# supplied by operator\n", encoding="utf-8")
        after = harness.run(t, prior=before)
    assert before["verdict"] == "DOCUMENTARY BLOCKER IDENTIFIED"
    assert after["verdict"] == \
        "NO DOCUMENTARY BLOCKER FOUND IN REVIEWED SOURCES"
    return before, after


def scenario_b() -> tuple:
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp) / "b"
        shutil.copytree(HERE / "corpus" / "core-b", t)
        before = harness.run(t)
        (t / "config" / "runtime.yaml").write_text(
            "# bumped by operator\nPROVIDES: runtime 3.0\n",
            encoding="utf-8")
        after = harness.run(t, prior=before)
    assert before["verdict"] == "DOCUMENTARY BLOCKER IDENTIFIED"
    assert after["verdict"] == \
        "NO DOCUMENTARY BLOCKER FOUND IN REVIEWED SOURCES"
    return before, after


def scenario_c() -> tuple:
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        (t / "guide.md").write_text(
            "REQUIRES: tool.py\nREQUIRES: license >= 2.0\n",
            encoding="utf-8")
        (t / "tool.py").write_text("x\n", encoding="utf-8")
        before = harness.run(t)
        (t / "readme.txt").write_text("unrelated note\n", encoding="utf-8")
        after = harness.run(t, prior=before)
    assert before["verdict"] == "INSUFFICIENT EVIDENCE"
    assert after["verdict"] == "INSUFFICIENT EVIDENCE"
    trans = {tr["subject"]: tr["state"]
             for tr in after["delta"]["transitions"]}
    assert trans.get("license") == "STILL UNCERTAIN", trans
    return before, after


def main():
    jobs = [
        ("A", "Missing asset", "studio-shot01", "core-a",
         "missing asset (A)", scenario_a),
        ("B", "Hidden incompatibility", "studio-shot01", "core-b",
         "version conflict (B)", scenario_b),
        ("C", "False reassurance", "studio-shot01", "synthetic-c",
         "unverified version fact (C)", scenario_c),
    ]
    for tag, title, project, scope, scenario, fn in jobs:
        before, after = fn()
        doc = doc_for(tag, title, project, scope, scenario,
                      before, after)
        out = HERE / f"closure-demo-{tag}.rendered.md"
        out.write_text("\n".join(doc), encoding="utf-8")
        print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
